// Writes /sw.js: precaches the site and trainer, versioned by a hash of every precached file,
// so any change to the site installs a new service worker that replaces the old cache.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const include = (rel) => {
  if (/^(tools|tests|node_modules|fulfillment-kit|\.git|\.vercel|\.claude)\//.test(rel)) return false;
  if (rel.startsWith('img/previews/') || rel === 'og-image.png' || rel === 'sw.js') return false;
  if (rel.startsWith('thank-you/')) return false; // confirmation pages are online-only
  return /\.(html|css|js|json|gz|svg|png|webmanifest|txt)$/.test(rel) && !/^(package(-lock)?\.json|vercel\.json)$/.test(rel) && !rel.endsWith('.LICENSE.txt') && rel !== 'robots.txt';
};
function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    const rel = path.relative(ROOT, p).split(path.sep).join('/');
    if (e.isDirectory()) { if (!/^(tools|tests|node_modules|fulfillment-kit|\.git|\.vercel|\.claude)$/.test(rel)) walk(p, out); }
    else if (include(rel)) out.push(rel);
  }
  return out;
}
const files = walk(ROOT).sort();
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = hash.digest('hex').slice(0, 12);
const urls = files.map((f) => '/' + f.replace(/(^|\/)index\.html$/, '$1'));

const sw = `/* Fiancho Chess service worker. Generated by tools/sw/build-sw.mjs — do not edit by hand. */
const VERSION = '${version}';
const CACHE = 'fiancho-' + VERSION;
const RUNTIME = 'fiancho-runtime';
const PRECACHE = ${JSON.stringify(urls, null, 0)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('fiancho-') && k !== CACHE && k !== RUNTIME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (req.mode === 'navigate') {
      // Pages: network first so updates appear straight away; the cached copy works offline.
      event.respondWith(
        fetch(req).then((res) => {
          if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(url.pathname, copy)); }
          return res;
        }).catch(() => caches.match(url.pathname, { ignoreSearch: true }).then((r) => r || caches.match('/404.html')))
      );
      return;
    }
    // Files: served from this version's cache, falling back to the network.
    event.respondWith(
      caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok && url.pathname.startsWith('/img/')) { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(req, copy)); }
        return res;
      }))
    );
    return;
  }
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    // Fonts: use the saved copy at once and refresh it in the background.
    event.respondWith(
      caches.open(RUNTIME).then((c) => c.match(req).then((hit) => {
        const net = fetch(req).then((res) => { if (res.ok || res.type === 'opaque') c.put(req, res.clone()); return res; }).catch(() => hit);
        return hit || net;
      }))
    );
  }
});
`;
fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: ${urls.length} files, version ${version}`);
